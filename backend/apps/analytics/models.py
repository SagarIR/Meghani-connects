from django.db import models
from django.conf import settings
from django.utils import timezone


class AnalyticsCache(models.Model):
    """Cache for computed analytics metrics"""
    metric_name = models.CharField(max_length=50, unique=True)
    metric_value = models.JSONField()
    period = models.CharField(max_length=20, blank=True)
    updated_on = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = 'analytics_cache'
        verbose_name = 'Analytics Cache'
        verbose_name_plural = 'Analytics Cache'

    def __str__(self):
        return f"{self.metric_name} ({self.updated_on})"


class ReorderRecommendation(models.Model):
    """
    Intelligent inventory replenishment recommendation generated by the Smart Reorder Engine.
    Requires manager review and approval lifecycle before PO creation.
    """
    URGENCY_CHOICES = [
        ('critical', 'Critical (≤ 3 days stock)'),
        ('high', 'High (≤ 7 days stock)'),
        ('medium', 'Medium (≤ 14 days stock)'),
    ]

    STATUS_CHOICES = [
        ('pending', 'Pending Manager Review'),
        ('approved', 'Approved by Manager'),
        ('rejected', 'Rejected by Manager'),
        ('snoozed', 'Snoozed'),
    ]

    product = models.ForeignKey('products.Product', on_delete=models.CASCADE, related_name='reorder_recommendations')
    current_stock = models.IntegerField(default=0)
    daily_velocity = models.DecimalField(max_digits=10, decimal_places=2, default=0.00)
    lead_time_days = models.PositiveIntegerField(default=7)
    safety_stock = models.PositiveIntegerField(default=0)
    reorder_point = models.PositiveIntegerField(default=0)
    suggested_quantity = models.PositiveIntegerField(default=1)
    estimated_stockout_date = models.DateField(null=True, blank=True)
    days_of_stock = models.DecimalField(max_digits=10, decimal_places=1, default=0.0)
    urgency = models.CharField(max_length=20, choices=URGENCY_CHOICES, default='medium')
    estimated_cost = models.DecimalField(max_digits=12, decimal_places=2, default=0.00)
    reason = models.TextField(blank=True, help_text="Plain-language explanation of calculations")
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='pending')
    approved_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True, blank=True, related_name='approved_reorders')
    approved_at = models.DateTimeField(null=True, blank=True)
    action_notes = models.TextField(blank=True)
    snooze_until = models.DateField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = 'reorder_recommendations'
        ordering = ['-urgency', '-created_at']
        indexes = [
            models.Index(fields=['status']),
            models.Index(fields=['urgency']),
            models.Index(fields=['product', 'status']),
        ]

    def __str__(self):
        return f"Reorder {self.product.name} ({self.suggested_quantity} units) - {self.status}"


class ABCProductClassification(models.Model):
    """
    Automated ABC classification for timepiece inventory based on cumulative Pareto contribution.
    """
    CLASS_CHOICES = [
        ('A', 'Class A (Top ~70-80% Contribution)'),
        ('B', 'Class B (Next ~15-20% Contribution)'),
        ('C', 'Class C (Bottom ~5-10% Contribution)'),
        ('unclassified', 'Unclassified (Insufficient Data)'),
    ]

    product = models.OneToOneField('products.Product', on_delete=models.CASCADE, related_name='abc_classification')
    classification = models.CharField(max_length=20, choices=CLASS_CHOICES, default='unclassified')
    revenue_contribution = models.DecimalField(max_digits=12, decimal_places=2, default=0.00)
    cumulative_revenue_percentage = models.DecimalField(max_digits=6, decimal_places=2, default=0.00)
    sales_volume = models.PositiveIntegerField(default=0)
    gross_profit_contribution = models.DecimalField(max_digits=12, decimal_places=2, default=0.00)
    inventory_value = models.DecimalField(max_digits=12, decimal_places=2, default=0.00)
    evaluation_period_days = models.PositiveIntegerField(default=90)
    evaluated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = 'abc_product_classifications'
        ordering = ['classification', '-revenue_contribution']
        indexes = [
            models.Index(fields=['classification']),
        ]

    def __str__(self):
        return f"{self.product.name} - Class {self.classification} ({self.cumulative_revenue_percentage}%)"


class BusinessAnomaly(models.Model):
    """
    Identifies unusual sales spikes, drops, unexpected stock reductions, or abnormal discounts.
    Serves as an investigation signal for management (never auto-blocks transactions).
    """
    CATEGORY_CHOICES = [
        ('sales_spike', 'Unusual Sales Spike'),
        ('sales_drop', 'Unusual Sales Drop'),
        ('stock_drop', 'Unexpected Stock Reduction'),
        ('abnormal_discount', 'Abnormal Discount Applied'),
        ('return_cancellation', 'Unusual Return or Cancellation Pattern'),
        ('demand_shift', 'Sudden Demand Shift'),
    ]

    SEVERITY_CHOICES = [
        ('low', 'Low'),
        ('medium', 'Medium'),
        ('high', 'High'),
        ('critical', 'Critical'),
    ]

    STATUS_CHOICES = [
        ('open', 'Open for Investigation'),
        ('investigating', 'Under Investigation'),
        ('resolved', 'Resolved'),
        ('dismissed', 'Dismissed as Normal'),
    ]

    category = models.CharField(max_length=30, choices=CATEGORY_CHOICES)
    severity = models.CharField(max_length=15, choices=SEVERITY_CHOICES, default='medium')
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='open')
    product = models.ForeignKey('products.Product', on_delete=models.SET_NULL, null=True, blank=True, related_name='anomalies')
    sale = models.ForeignKey('sales.Sale', on_delete=models.SET_NULL, null=True, blank=True, related_name='anomalies')
    audit_log = models.ForeignKey('core.AuditLog', on_delete=models.SET_NULL, null=True, blank=True, related_name='anomalies')
    observed_value = models.DecimalField(max_digits=12, decimal_places=2)
    expected_baseline = models.DecimalField(max_digits=12, decimal_places=2)
    deviation_score = models.DecimalField(max_digits=8, decimal_places=2, help_text="Statistical Z-Score or multiplier")
    explanation = models.TextField()
    recommended_action = models.TextField()
    detected_at = models.DateTimeField(auto_now_add=True)
    resolved_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True, blank=True, related_name='resolved_anomalies')
    resolved_at = models.DateTimeField(null=True, blank=True)
    resolution_notes = models.TextField(blank=True)

    class Meta:
        db_table = 'business_anomalies'
        ordering = ['-detected_at']
        indexes = [
            models.Index(fields=['category']),
            models.Index(fields=['severity']),
            models.Index(fields=['status']),
            models.Index(fields=['detected_at']),
        ]

    def __str__(self):
        return f"[{self.severity.upper()}] {self.get_category_display()} - {self.detected_at.strftime('%Y-%m-%d')}"
